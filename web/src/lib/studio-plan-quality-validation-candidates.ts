export const planQualityValidationCandidateSchema = z
  .object({
    id: z.string().regex(/^validation-candidate-[a-z0-9-]+$/),
    label: z.string().min(1).max(200),
    synthetic: z.literal(true),
    status: z.literal("validation-candidate"),
    authoredBy: z.literal("ai"),
    humanAnswerKey: z.null(),
    independentHoldoutConfirmed: z.literal(false),
    performanceEvaluation: z.literal("not-performed"),
    catalogRegistration: z.literal("not-registered"),
    sector: z.enum(validationCandidateSectors),
    applicationKind: z.enum(["new", "renewal"]),
    materialDesign: z.enum(["connected-narrative", "intentional-gap", "intentional-conflict"]),
    challengeTags: z.array(z.enum(validationCandidateChallenges)).min(1),
    authoringNotes: z.array(z.string().min(1).max(2000)).min(1),
    company: caseSchema,
    candidate: candidateSchema,
  })
  .strict()
  .superRefine((value, context) => {
    if (value.company.profile.applicationKind !== value.applicationKind)
      context.addIssue({ code: "custom", message: "신청 유형 메타데이터가 일치해야 합니다." });
    if (value.company.sources.length < 4)
      context.addIssue({ code: "custom", message: "서로 구분된 합성 자료 묶음이 필요합니다." });
  });
export type PlanQualityValidationCandidate = z.infer<typeof planQualityValidationCandidateSchema>;

